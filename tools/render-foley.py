"""Render the game's original mono Foley library. Requires numpy and scipy."""
from pathlib import Path
import json
import numpy as np
from scipy.io import wavfile
from scipy.signal import butter, sosfilt

out = Path(__file__).resolve().parents[1] / 'dist/immersive/foley'
rate = 24000
rng = np.random.default_rng(62017)
clips = {}

def time(seconds):
    return np.arange(round(seconds * rate)) / rate

def noise(t, lo, hi):
    sos = butter(2, [lo, hi], btype='bandpass', fs=rate, output='sos')
    return sosfilt(sos, rng.normal(size=len(t)))

def strike(name, length, modes, attack, tick):
    t = time(length)
    body = sum(a * np.sin(2*np.pi*f*t) * np.exp(-t/decay) for f, a, decay in modes)
    clips[name] = (body + tick*noise(t,900,6200)*np.exp(-t/.012)) * (1-np.exp(-t/attack))

def friction(name, length, bands, strokes):
    t = time(length)
    grain = sum(a*noise(t,lo,hi) for lo,hi,a in bands)
    envelope = sum(a*np.exp(-.5*((t-center)/width)**2) for center,width,a in strokes)
    clips[name] = grain*envelope

strike('temple-bell',3.6,[(186,1,1.18),(372,.56,.87),(451,.37,.65),(703,.36,.79),(1013,.24,.46),(1410,.14,.32)],.005,.42)
strike('harbor-bell',2.2,[(367,1,.61),(701,.58,.49),(981,.45,.41),(1450,.26,.31)],.004,.65)
strike('glass',1.9,[(504,1,.59),(799,.53,.46),(1306,.33,.44),(2193,.19,.18)],.012,.08)
strike('shard',.48,[(1310,1,.09),(1978,.56,.12),(3021,.35,.07),(4193,.2,.04)],.001,1)
strike('key',.49,[(890,1,.055),(1577,.69,.08),(2473,.44,.045)],.001,1.2)
strike('brass-tap',.36,[(370,1,.054),(724,.55,.041),(1322,.24,.031)],.002,.8)
strike('knuckle',.32,[(125,1,.055),(278,.61,.038),(416,.24,.023)],.002,.92)
strike('crate',.68,[(86,1,.09),(157,.74,.075),(294,.39,.058)],.003,1.65)
friction('paper',.68,[(450,1300,.38),(1450,5100,.8)],[(.11,.05,.85),(.24,.026,.71),(.35,.08,.48),(.5,.03,.28)])
friction('cloth',.78,[(180,1100,1),(1000,2800,.37)],[(.23,.10,1),(.46,.12,.49)])
friction('pencil',.72,[(1150,2500,.83),(2450,5400,.67)],[(.08,.032,1),(.23,.052,.8),(.43,.043,.94),(.58,.03,.64)])
friction('bolt',.56,[(100,490,1),(780,2300,.65)],[(.12,.022,.95),(.26,.071,.7),(.43,.014,.99)])
friction('boot',.39,[(75,310,1.9),(495,1600,.68),(1700,4200,.26)],[(.045,.018,1),(.12,.038,.66),(.22,.055,.17)])
t=time(.39)
clips['boot'] += .45*np.sin(2*np.pi*(105*t-62*t*t))*np.exp(-t/.08)*(1-np.exp(-t/.009))
friction('lap',1.6,[(180,570,.8),(570,1800,.5)],[(.46,.19,.9),(.8,.14,.52),(1.08,.14,.25)])
t=time(1.6)
for at,f in [(.51,620),(.62,810),(.88,541)]:
    dt=np.maximum(0,t-at)
    clips['lap']+=.13*np.sin(2*np.pi*(f*dt+1700*dt**2))*np.exp(-dt/.031)
friction('rope',.88,[(230,850,1),(1100,2500,.44)],[(.22,.11,.8),(.47,.07,.73),(.65,.04,.46)])
t=time(1.1)
clips['creak']=np.sin(2*np.pi*(141*t+22*t*t)+.8*np.sin(48*t))*(.36+np.sin(72*t)**2)*np.sin(np.pi*t/t[-1])**2 + noise(t,270,1750)*.16*np.sin(np.pi*t/t[-1])**2
friction('stone',1.6,[(50,380,1.5),(510,2000,.7)],[(.2,.09,.65),(.58,.25,.99),(1.01,.22,.8),(1.36,.07,.55)])
t=time(3.6)
# Indistinct plaza voices. Each voice has independently shifting vowel bands and syllable lengths.
crowd=np.zeros(len(t))
for _ in range(16):
    f=rng.uniform(97,218)
    phase=2*np.pi*f*t+.9*np.sin(t*rng.uniform(6,12)+rng.uniform(0,6))
    formants=[(rng.uniform(390,760),150),(rng.uniform(850,1800),290)]
    voice=sum(np.sin(h*phase)*sum(np.exp(-.5*((h*f-c)/w)**2) for c,w in formants)/h for h in range(2,19))
    syllables=np.maximum(0,np.sin(t*rng.uniform(8,18)+rng.uniform(0,6)))**1.3
    crowd+=voice*syllables*(.45+.4*np.sin(t*rng.uniform(2,5)+rng.uniform(0,6)))
clips['market']=crowd*np.sin(np.pi*t/t[-1])**1.4
t=time(2.35)
clips['resonance']=(np.sin(2*np.pi*233*t)+.46*np.sin(2*np.pi*351*t)+.24*np.sin(2*np.pi*698*t))*(1-np.exp(-t/.37))*np.exp(-t/.68)*(.74+.26*np.cos(2*np.pi*2*t))
pieces=[]; offsets={}; cursor=0
for name,y in clips.items():
    y[:48]*=np.linspace(0,1,48)
    y[-240:]*=np.linspace(1,0,240)
    y=y/max(abs(y))*.89
    offsets[name]=[cursor/rate,len(y)/rate]
    pieces.extend([y,np.zeros(240)])
    cursor+=len(y)+240
wavfile.write(out/'materials.wav',rate,np.int16(np.concatenate(pieces)*32767))
(out/'offsets.mjs').write_text('// Generated by tools/render-foley.py\nexport const offsets='+json.dumps(offsets,indent=2)+';\n')
